META = 'CREATE TABLE IF NOT EXISTS meta (clave TEXT COLLATE "C" PRIMARY KEY, valor TEXT, actualizado TEXT)'


def version(con):
    r = con.execute("SELECT valor FROM meta WHERE clave='esquema_version'").fetchone()
    return int(r["valor"]) if r else 0


def migrar(con):
    """Aplica las migraciones pendientes. `con` es una conexión en modo transacción (no autocommit).
    Devuelve la lista de versiones aplicadas en esta llamada."""
    from comun import ahora, iso
    aplicadas = []
    with con.transaction():
        con.execute("SELECT pg_advisory_xact_lock(%s)", (CANDADO_MIGRACION,))
        con.execute(META)
        actual = version(con)
        for v, desc, sql in MIGRACIONES:
            if v <= actual:
                continue
            with con.transaction():           # savepoint: si una falla, no queda a medias
                con.execute(sql)
                con.execute("INSERT INTO meta (clave, valor, actualizado) VALUES ('esquema_version', %s, %s) "
                            "ON CONFLICT (clave) DO UPDATE SET valor=excluded.valor, actualizado=excluded.actualizado",
                            (str(v), iso(ahora())))
            aplicadas.append(v)
            print(f"Base de datos: migración {v} aplicada ({desc})")
    return aplicadas


def meta_get(con, clave):
    r = con.execute("SELECT valor FROM meta WHERE clave=%s", (clave,)).fetchone()
    return r["valor"] if r else None


def meta_set(con, clave, valor):
    from comun import ahora, iso
    con.execute("INSERT INTO meta (clave, valor, actualizado) VALUES (%s, %s, %s) "
                "ON CONFLICT (clave) DO UPDATE SET valor=excluded.valor, actualizado=excluded.actualizado",
                (clave, valor, iso(ahora())))


def filas_por_tabla(con):
    """{tabla: cantidad de filas} de las tablas de datos."""
